/** Расклад по умолчанию. */
export const DEFAULT_SPREAD_ID = "triptych";

const SPREAD_BY_ID: ReadonlyMap<string, Spread> = new Map(
  SPREADS.map((s) => [s.id, s]),
);

/** Находит расклад по идентификатору. */
export function spreadById(id: string): Spread | undefined {
  return SPREAD_BY_ID.get(id);
}
