/** Архетип ранга 1..14, общий для всех мастей. */
export interface RankArchetype {
  readonly rank: number;
  /** Имя ранга (Туз, Двойка … Лорд). */
  readonly name: string;
  /** Краткий титул-архетип. */
  readonly archetype: string;
  /** Прямой смысл ранга (домен подставляется отдельно). */
  readonly upright: string;
  /** Перевёрнутый смысл ранга. */
  readonly reversed: string;
  /** Ключевые слова ранга (прямое). */
  readonly uprightKeywords: readonly string[];
  /** Ключевые слова ранга (перевёрнутое). */
  readonly reversedKeywords: readonly string[];
}

